def load_yaml(path: Path) -> Any:
    """A YAML config file's content."""
    try:
        text = Path(path).read_text(encoding="utf-8")
    except FileNotFoundError as exc:
        raise ConfigError(f"config file not found: {path}") from exc
    except UnicodeDecodeError as exc:
        raise ConfigError(f"cannot read {path}: it is not UTF-8 text (save it as UTF-8): {exc}") from exc
    except OSError as exc:
        raise ConfigError(f"cannot read {path}: {exc}") from exc
    try:
        return yaml.safe_load(text)
    except yaml.YAMLError as exc:
        raise ConfigError(f"{Path(path).name} is not valid YAML: {exc}") from exc


# --- process.yaml -------------------------------------------------------------


class EstimateConfig(BaseModel):
    model_config = ConfigDict(extra="forbid")

    basis: Literal["hours", "points"]
    field: Literal["story_points", "original_estimate"]
    hours_per_point: float | None = None

    @model_validator(mode="after")
    def _consistent(self) -> EstimateConfig:
        if self.basis == "points":
            if self.field != "story_points":
                raise ValueError("estimate basis 'points' needs field 'story_points'")
            if not self.hours_per_point or self.hours_per_point <= 0:
                raise ValueError("estimate basis 'points' needs hours_per_point > 0")
        elif self.field != "original_estimate":
            raise ValueError("estimate basis 'hours' needs field 'original_estimate'")
        return self


class CreditConfig(BaseModel):
    """Whom a board's tickets count for, until an admin changes it (GET /people/credit)."""

    model_config = ConfigDict(extra="forbid")

    source: Literal["auto", "assignee", "field"] = "auto"
    field: str | None = None  # a people field's logical name in fields.yaml, exactly when source is "field"

    @model_validator(mode="after")
    def _consistent(self) -> CreditConfig:
        if self.source != "field":
            if self.field is not None:
                raise ValueError(f"credit source {self.source!r} takes no field")
        elif self.field is None:
            raise ValueError("credit source 'field' needs a field")
        elif self.field not in PEOPLE_FIELDS:
            raise ValueError(f"credit field {self.field!r} is not a people field: one of {', '.join(PEOPLE_FIELDS)}")
        return self


class ProjectProcess(BaseModel):
    model_config = ConfigDict(extra="forbid")

    # The board's name as people know it (the dashboard's board picker shows it); None shows the key.
    name: str | None = Field(default=None, min_length=1, max_length=80)
    status_to_stage: dict[str, str]
    estimate: EstimateConfig
    # Stage -> where its evidence lives; null means Jira can't prove it today.
    evidence: dict[str, dict[str, Any] | None] = Field(default_factory=dict)
    # A synthetic project (the demo) has no Jira site behind it: nothing links to Jira.
    synthetic: bool = False
    stages_since: dict[str, date] = Field(default_factory=dict)
    credit: CreditConfig = Field(default_factory=CreditConfig)

    _folded: dict[str, str] = PrivateAttr(default_factory=dict)
    _automatic: bool = PrivateAttr(default=False)

    def model_post_init(self, _context: Any) -> None:
        self._folded = {status.casefold(): stage for status, stage in self.status_to_stage.items()}

    @property
    def automatic(self) -> bool:
        """Whether this mapping was worked out by the service rather than written in process.yaml."""
        return self._automatic

    def stage_of(self, status: str | None) -> str | None:
        """James's stage for a Jira status name (case-insensitive), or None if unmapped."""
        if status is None:
            return None
        return self._folded.get(status.casefold())


class ProcessConfig(BaseModel):
    model_config = ConfigDict(extra="forbid")

    process_version: str
    stages: list[str]
    start_stage: str = "development"
    done_stage: str = "done"
    projects: dict[str, ProjectProcess]

    @model_validator(mode="after")
    def _check(self) -> ProcessConfig:
        if len(set(self.stages)) != len(self.stages):
            raise ValueError("stages must be unique")
        for name in (self.start_stage, self.done_stage):
            if name not in self.stages:
                raise ValueError(f"stage {name!r} is not in stages")
        if self.stages.index(self.start_stage) >= self.stages.index(self.done_stage):
            raise ValueError("start_stage must come before done_stage")
        for key, project in self.projects.items():
            folded = [status.casefold() for status in project.status_to_stage]
            if len(set(folded)) != len(folded):
                raise ValueError(f"{key}: status names must be unique ignoring case")
            for status, stage in project.status_to_stage.items():
                if stage not in self.stages:
                    raise ValueError(f"{key}: status {status!r} maps to unknown stage {stage!r}")
            for stage in project.evidence:
                if stage not in self.stages:
                    raise ValueError(f"{key}: evidence for unknown stage {stage!r}")
            for stage in project.stages_since:
                if stage not in project.status_to_stage.values():
                    raise ValueError(f"{key}: stages_since names {stage!r}, which no status maps to")
        return self

    @classmethod
    def load(cls, path: Path) -> ProcessConfig:
        data = load_yaml(path)
        try:
            return cls.model_validate(data)
        except ValidationError as exc:
            raise ConfigError(f"{Path(path).name} is invalid:\n{exc}") from exc

    def with_projects(self, projects: Mapping[str, ProjectProcess]) -> ProcessConfig:
        if not projects:
            return self
        return self.model_copy(update={"projects": {**self.projects, **projects}})

    def project(self, key: str) -> ProjectProcess:
        """The board's mapping."""
        try:
            return self.projects[key]
        except KeyError:
            raise ConfigError(f"project {key!r} is not configured in process.yaml") from None

    def stage_of(self, project: str, status: str | None) -> str | None:
        return self.project(project).stage_of(status)

    def ordered_stages(self, project: str, at: str | None = None) -> list[str]:
        """The stages this project's workflow actually maps, in process order."""
        config = self.project(project)
        mapped = set(config.status_to_stage.values())
        if at:
            day = at[:10]
            mapped -= {stage for stage, since in config.stages_since.items() if day < since.isoformat()}
        return [stage for stage in self.stages if stage in mapped]

    def work_stages(self) -> list[str]:
        """Stages from start_stage up to, not including, done_stage."""
        start = self.stages.index(self.start_stage)
        end = self.stages.index(self.done_stage)
        return self.stages[start:end]

    def estimate_for(self, project: str) -> EstimateConfig:
        return self.project(project).estimate

    def has_evidence(self, project: str, name: str) -> bool:
        return self.project(project).evidence.get(name) is not None

    def missing_evidence(self, project: str) -> list[str]:
        """Stages whose evidence this project doesn't record, in process order."""
        config = self.project(project)
        mapped = set(config.status_to_stage.values())
        implied = {stage for stage in self.work_stages()[1:] if stage not in mapped}
        return [
            stage
            for stage in self.stages
            if (stage in config.evidence and config.evidence[stage] is None)
            or (stage in implied and stage not in config.evidence)
        ]


