class FieldRef(BaseModel):
    model_config = ConfigDict(extra="forbid")

    id: str
    name: str
    custom_type: str | None = None


class FieldsConfig(BaseModel):
    model_config = ConfigDict(extra="forbid")

    generated_at: str | None = None
    site: str | None = None
    # Logical name -> field on this site; None when the site has no such field.
    fields: dict[str, FieldRef | None] = Field(default_factory=dict)

    @classmethod
    def load(cls, path: Path) -> FieldsConfig:
        data = load_yaml(path)
        try:
            return cls.model_validate(data or {})
        except ValidationError as exc:
            raise ConfigError(f"{Path(path).name} is invalid:\n{exc}") from exc

    def dump(self, path: Path) -> None:
        body = yaml.safe_dump(self.model_dump(mode="json"), sort_keys=False, allow_unicode=True)
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = path.with_name(f".{path.name}.tmp")
        try:
            temporary.write_text(FIELDS_HEADER + body, encoding="utf-8")
            os.replace(temporary, path)
        finally:
            temporary.unlink(missing_ok=True)

    def id_of(self, logical: str) -> str | None:
        ref = self.fields.get(logical)
        return ref.id if ref else None

    def people_fields(self) -> dict[str, FieldRef]:
        """The site's fields that hold people, by logical name"""
        return {logical: ref for logical, ref in self.fields.items()
                if ref is not None and (ref.custom_type or "").endswith(PEOPLE_TYPES)}

    def tracked_changelog_fields(self) -> dict[str, str]:
        """Jira field id -> logical name for every field whose history we keep."""
        tracked = dict(SYSTEM_TRACKED)
        for logical in CUSTOM_TRACKED:
            field_id = self.id_of(logical)
            if field_id:
                tracked[field_id] = logical
        return tracked

    def search_fields(self) -> list[str]:
        """Issue fields to request from search: the base set plus every resolved custom field."""
        out = list(BASE_SEARCH_FIELDS)
        for ref in self.fields.values():
            if ref and ref.id not in out:
                out.append(ref.id)
        return out
